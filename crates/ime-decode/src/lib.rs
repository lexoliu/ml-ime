    /// `decode_many` over one record, as every call here decodes only one.
    fn decode<E: Emission, T: Transition>(
        batch: &Candidates,
        emission: E,
        transition: &T,
        context: Option<&str>,
        options: &BeamOptions,
    ) -> Result<Vec<Hypothesis>, DecodeError> {
        decode_many(
            &[Record {
                candidates: batch,
                emission,
                context,
            }],
            transition,
            options,
        )
        .map(|mut results| results.pop().expect("one record decodes to one result"))
    }

    /// A transition model that likes exactly one sentence: each character in the
    /// table scores well after its listed predecessor, everything else scores
    /// badly. Enough to prove the search finds what the scores point at.
    struct Preference {
        bigrams: HashMap<(Option<CharId>, CharId), f32>,
    }

    impl Preference {
        fn new(lexicon: &Lexicon, sentence: &str) -> Self {
            let ids: Vec<CharId> = sentence
                .chars()
                .map(|ch| lexicon.id_of(ch).expect("sentence is in the lexicon"))
                .collect();
            let mut bigrams = HashMap::new();
            let mut previous = None;
            for id in ids {
                bigrams.insert((previous, id), 0.0);
                previous = Some(id);
            }
            Self { bigrams }
        }
    }

    impl Transition for Preference {
        const HISTORY: usize = 1;

        type State = Option<CharId>;

        fn start(&self, _context: Option<&str>, _asked: &Asked<'_>) -> Self::State {
            None
        }

        fn score(&self, state: &Self::State, candidate: CharId) -> f32 {
            *self.bigrams.get(&(*state, candidate)).unwrap_or(&-10.0)
        }

        fn finish(&self, _state: &Self::State) -> f32 {
            0.0
        }

        fn advance(&self, steps: &[(&Self::State, CharId, Asked<'_>)]) -> Vec<Self::State> {
            steps.iter().map(|(_, ch, _)| Some(*ch)).collect()
        }
    }

