    #[test]
    fn a_batch_decodes_each_record_as_if_alone() {
        let (table, lexicon) = fixture();
        let batches = [
            candidates("zhongguo", &table, &lexicon),
            candidates("nihao", &table, &lexicon),
        ];
        let transition = Preference::new(&lexicon, "中国");
        let options = BeamOptions::default();
        let together = decode_many(
            &batches
                .iter()
                .map(|batch| Record {
                    candidates: batch,
                    emission: Uniform,
                    context: None,
                })
                .collect::<Vec<_>>(),
            &transition,
            &options,
        )
        .expect("the batch decodes");
        assert_eq!(together.len(), batches.len());
        for (batch, results) in batches.iter().zip(&together) {
            let alone = decode(batch, Uniform, &transition, None, &options).expect("decodes");
            assert_eq!(results.len(), alone.len());
            for (batched, solo) in results.iter().zip(&alone) {
                assert_eq!(batched.chars(), solo.chars());
                assert_eq!(
                    batched.score().to_bits(),
                    solo.score().to_bits(),
                    "a batched record scores bit-identically to the solo run"
                );
                assert_eq!(batched.path(), solo.path());
            }
        }
    }

    #[test]
    fn the_list_keeps_the_runner_up_first_character() {
        struct PerPosition {
            scores: HashMap<(usize, CharId), f32>,
        }
        impl Emission for PerPosition {
            fn score(&self, _path: usize, position: usize, candidate: CharId) -> f32 {
                *self.scores.get(&(position, candidate)).unwrap_or(&-20.0)
            }
        }
        /// Scores nothing and remembers two characters, so prefixes that
        /// diverge at position 0 are not merged away before they can finish.
        struct Flat;
        impl Transition for Flat {
            const HISTORY: usize = 2;
            type State = ();
            fn start(&self, _context: Option<&str>, _asked: &Asked<'_>) -> Self::State {}
            fn score(&self, _state: &Self::State, _candidate: CharId) -> f32 {
                0.0
            }
            fn finish(&self, _state: &Self::State) -> f32 {
                0.0
            }
            fn advance(&self, steps: &[(&Self::State, CharId, Asked<'_>)]) -> Vec<Self::State> {
                vec![(); steps.len()]
            }
        }
        let (table, lexicon) = fixture();
        let batch = candidates("tashi", &table, &lexicon);
        let ta = lexicon.id_of('他').expect("他");
        let ta2 = lexicon.id_of('她').expect("她");
        // `tashi` reads as `ta` + `shi`; the second position admits enough
        // characters for the stronger first character's tails to fill top-8.
        let path = batch
            .paths()
            .iter()
            .find(|path| path.len() == 2)
            .expect("tashi reads as two syllables");
        let second = &path.positions()[1];
        assert!(second.len() >= 10, "the fixture needs a wide tail");
        assert!(path.positions()[0].contains(&ta2));
        let mut scores = HashMap::new();
        // The runner-up is close behind, and at least eight of the winner's
        // tails are closer -- so a score-ordered top-8 cannot reach it, while
        // the 16-wide beam still carries it to the end.
        scores.insert((0, ta), 0.0);
        scores.insert((0, ta2), -0.2);
        let mut tail = 0.0f32;
        for &ch in second {
            scores.insert((1, ch), tail);
            tail -= 0.02;
        }
        let best = decode(
            &batch,
            PerPosition { scores },
            &Flat,
            None,
            &BeamOptions::default(),
        )
        .expect("tashi decodes");
        assert_eq!(best[0].chars()[0], ta, "top-1 stays the best hypothesis");
        assert!(
            best.iter().any(|h| h.chars()[0] == ta2),
            "the runner-up reading of position 0 is listed: {:?}",
            best.iter().map(|h| h.text(&lexicon)).collect::<Vec<_>>()
        );
    }

    #[test]
    fn the_beam_keeps_a_runner_up_reading_alive() {
        struct PerPosition {
            scores: HashMap<(usize, CharId), f32>,
        }
        impl Emission for PerPosition {
            fn score(&self, _path: usize, position: usize, candidate: CharId) -> f32 {
                *self.scores.get(&(position, candidate)).unwrap_or(&-20.0)
            }
        }
        let (table, lexicon) = fixture();
        let batch = candidates("tashi", &table, &lexicon);
        let ta = lexicon.id_of('他').expect("他");
        let ta2 = lexicon.id_of('她').expect("她");
        let path = batch
            .paths()
            .iter()
            .find(|path| path.len() == 2)
            .expect("tashi reads as two syllables");
        let second = &path.positions()[1];
        // `她` trails `他` by 0.2 at position 0, and every `他` tail beats
        // every `她` tail, so under a one-character history each `她x`
        // merges into `他x` -- without a guard no `她` state can reach
        // position 1 at all.
        assert!(second.len() >= 10, "the fixture needs a wide tail");
        assert!(path.positions()[0].contains(&ta2));
        let mut scores = HashMap::new();
        scores.insert((0, ta), 0.0);
        scores.insert((0, ta2), -0.2);
        let mut tail = 0.0f32;
        for &ch in second {
            scores.insert((1, ch), tail);
            tail -= 0.02;
        }
        let narrow = BeamOptions {
            diversity_gap: 0.0,
            ..BeamOptions::default()
        };
        let plain = decode(
            &batch,
            PerPosition {
                scores: scores.clone(),
            },
            &NoTransition,
            None,
            &narrow,
        )
        .expect("tashi decodes");
        assert!(
            plain.iter().all(|h| h.chars()[0] == ta),
            "without the guard every survivor reads the winner's character: {:?}",
            plain.iter().map(|h| h.text(&lexicon)).collect::<Vec<_>>()
        );
        let guarded = BeamOptions {
            diversity_gap: 0.5,
            diversity_chars: 2,
            ..BeamOptions::default()
        };
        let best = decode(
            &batch,
            PerPosition { scores },
            &NoTransition,
            None,
            &guarded,
        )
        .expect("tashi decodes");
        assert_eq!(best[0].chars()[0], ta, "top-1 stays the best hypothesis");
        assert!(
            best.iter().any(|h| h.chars()[0] == ta2),
            "the guarded runner-up survives the beam and reaches the list: {:?}",
            best.iter().map(|h| h.text(&lexicon)).collect::<Vec<_>>()
        );
    }

    /// Every character of the lexicon, as an emittable set.
    fn every_character(lexicon: &Lexicon) -> Emittable {
        let source: String = lexicon
            .characters()
            .iter()
            .flat_map(|&ch| [ch, '\n'])
            .collect();
        Emittable::parse(&source, lexicon).expect("the lexicon's own characters")
    }

    /// *input*'s readings with the arcs of a one-line idiom lexicon.
    fn with_idiom(
        input: &str,
        idiom: &str,
        table: &SyllableTable,
        lexicon: &Lexicon,
    ) -> Candidates {
        let options = offline();
        let lattice = SegmentLattice::build(input, table, &options).expect("input reads");
        let readings = lattice.k_best(&options);
        let (words, _) = WordLexicon::parse(
            &format!("{idiom}\tidiom\n"),
            &["idiom"],
            lexicon,
            table,
            &every_character(lexicon),
        )
        .expect("the lexicon reads");
        Candidates::build(&readings, lexicon)
            .expect("masks are non-empty")
            .with_arcs(&readings, input, &words, lexicon, table, &options)
    }

    /// Scores looked up by (position, character); everything else -20.
    struct PerPosition(HashMap<(usize, CharId), f32>);

    impl Emission for &PerPosition {
        fn score(&self, _path: usize, position: usize, candidate: CharId) -> f32 {
            *self.0.get(&(position, candidate)).unwrap_or(&-20.0)
        }
    }

    /// The `yffs` fixture: 一帆风顺 wins as a whole, but its first character
    /// loses position 0 to 夜 by five nats, so a one-wide beam drops it.
    fn yffs(lexicon: &Lexicon, first: f32) -> (PerPosition, Preference) {
        let id = |ch| lexicon.id_of(ch).expect("in the lexicon");
        let mut scores = HashMap::new();
        scores.insert((0, id('一')), first);
        scores.insert((0, id('夜')), 0.0);
        for (position, ch) in [(1, '帆'), (2, '风'), (3, '顺')] {
            scores.insert((position, id(ch)), 0.0);
        }
        (PerPosition(scores), Preference::new(lexicon, "一帆风顺"))
    }

    fn narrow_beam() -> BeamOptions {
        BeamOptions {
            beam_width: std::num::NonZeroUsize::new(1).expect("1 is not zero"),
            diversity_gap: 0.0,
            arc_prior: 0.0,
            ..BeamOptions::default()
        }
    }

    #[test]
    fn an_arc_carries_its_idiom_through_a_beam_that_drops_its_first_character() {
        let (table, lexicon) = fixture();
        // 一 locally: -15 (emission). 夜 locally: 0 - 10 (the bigram).
        // Whole: 一帆风顺 -15, 夜帆风顺 -20.
        let (emission, transition) = yffs(&lexicon, -15.0);
        let plain = candidates("yffs", &table, &lexicon);
        let without =
            decode(&plain, &emission, &transition, None, &narrow_beam()).expect("yffs decodes");
        assert_ne!(
            without[0].text(&lexicon),
            "一帆风顺",
            "the narrow beam prunes it"
        );
        let arcs = with_idiom("yffs", "一帆风顺", &table, &lexicon);
        let with =
            decode(&arcs, &emission, &transition, None, &narrow_beam()).expect("yffs decodes");
        assert_eq!(with[0].text(&lexicon), "一帆风顺");
        assert!((with[0].score() - without[0].score()).abs() > 1.0);
    }

